// Build a single module for Cloudflare Dashboard without external dependencies.
import {readFile, writeFile} from 'node:fs/promises';
const root = new URL('../integrations/cloudflare/', import.meta.url);
const newline = String.fromCharCode(10);
const parts = [];
for (const name of ['telegram.mjs', 'private-queue.mjs', 'full.mjs']) {
  let text = await readFile(new URL(name, root), 'utf8');
  if (name === 'telegram.mjs') text = text.split('export default {')[0];
  text = text.split(newline).filter(line => !line.startsWith('import ')).join(newline);
  text = text.replaceAll('export async function ', 'async function ').replaceAll('export function ', 'function ');
  parts.push(text.trim());
}
const output = '// GENERATED by node scripts/build_cloudflare.mjs; edit the source modules.' + newline
  + '// SPDX-License-Identifier: AGPL-3.0-only; MIT portions: THIRD_PARTY_LICENSES.md.' + newline
  + parts.join(newline + newline) + newline;
const target = new URL('dashboard-worker.mjs', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Dashboard bundle is stale.');
} else {
  await writeFile(target, output);
}
console.log('Cloudflare dashboard module verified.');
